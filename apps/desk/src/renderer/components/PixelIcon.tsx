export type PixelIconName = keyof typeof BITMAPS;
export const PIXEL_ICON_NAMES = Object.keys(BITMAPS) as PixelIconName[];

/** Horizontal runs of filled pixels, so each row is a few rects instead of 16. */
function runs(rows: readonly string[]): { x: number; y: number; w: number }[] {
  const out: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const on = row[x] === "#";
      if (on && start < 0) start = x;
      if (!on && start >= 0) {
        out.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });
  return out;
}

const RUNS = Object.fromEntries(
  Object.entries(BITMAPS).map(([k, v]) => [k, runs(v)]),
) as Record<PixelIconName, ReturnType<typeof runs>>;

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 16,
  className,
}: {
  name: PixelIconName;
  size?: number;
  className?: string;
}) {
  return (
    <svg
      className={`pixel-icon${className !== undefined ? ` ${className}` : ""}`}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {RUNS[name].map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} fill="currentColor" />
      ))}
    </svg>
  );
});
